"""Export cross-document labels as TeX inputs preserved by submission systems."""
from pathlib import Path
import sys


def groups(text):
    result = []
    depth = 0
    for index, char in enumerate(text):
        if char == "{" and (index == 0 or text[index - 1] != "\\"):
            if depth == 0:
                start = index + 1
            depth += 1
        elif char == "}" and (index == 0 or text[index - 1] != "\\"):
            depth -= 1
            if depth == 0:
                result.append(text[start:index])
    return result


root = Path(__file__).resolve().parent
for stem in sys.argv[1:]:
    prefix, output = {
        "fwm-and-coupler": ("M-", "main-paper-references.tex"),
        "supplement": ("S-", "supplement-references.tex"),
    }[stem]
    lines = ["% Generated by export-references.py; regenerate with make."]
    for line in (root / (stem + ".aux")).read_text().splitlines():
        if line.startswith("\\newlabel{"):
            label, value = groups(line[len("\\newlabel"):])
            fields = groups(value)
            if len(fields) != 5:
                raise ValueError(f"Unexpected label data: {line}")
            fields[4] = stem + ".pdf"
            lines.append("\\newlabel{" + prefix + label + "}{"
                         + "".join("{" + field + "}" for field in fields) + "}")
    if len(lines) == 1:
        raise ValueError(f"No labels found for {stem}")
    destination = root / output
    content = "\n".join(lines) + "\n"
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)
